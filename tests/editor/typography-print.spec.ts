/**
 * M21 §5: typography reaches the exported PDF.
 *
 * ## What can honestly be claimed about a PDF
 *
 * Not that it is pixel-identical to the screen. It is not, and M21 does not claim it: Chromium's
 * print engine re-shapes text, may substitute a font for one it cannot embed, and line breaking
 * differs. A test asserting screen/PDF equality would be asserting something untrue until it failed
 * for a reason nobody could act on.
 *
 * What *is* provable, and what this file proves:
 *
 *  - **The authored font families are the ones the PDF embeds.** `/BaseFont` entries are read out of
 *    the generated bytes. This is the strong one: it can only contain a family the print engine
 *    actually resolved, so a `font-family` that never reached the sheet cannot appear here however
 *    plausible the CSS looks.
 *  - **Page count and sheet geometry** are unaffected by typography -- a document that renders is a
 *    document that prints, whatever its font.
 *  - **Arabic and combining marks survive export**, as extracted text. Character *order* and
 *    *presence* are properties of the content stream, not of the screen, so they are legitimately
 *    assertable; glyph *shaping* is not.
 *
 * The generated PDF is parsed with a regular expression over its bytes, the same technique
 * `print-mixed-size.spec.ts` uses for `/MediaBox`, and for the same reason: nothing short of reading
 * the real file answers these questions.
 */

import type { Page } from '@playwright/test';
import { expect, settle, test } from './helpers';
import { mountFixture } from '../visual/harness';

/** A two-frame document: two families, two sizes, mixed formatting, alignment, and a soft break. */
const TYPOGRAPHY_FIXTURE = `() => ({
  formatVersion: 3, id: 'typo', name: 'Typography',
  pageSetup: { fixedSize: true, defaultSize: { width: 210, height: 297, unit: 'mm', orientation: 'portrait' }, resizeBehaviour: 'crop' },
  styles: [],
  assets: {},
  pages: [{
    id: 'p1', name: '1',
    size: { width: 210, height: 297, unit: 'mm', orientation: 'portrait' },
    background: { type: 'solid', color: '#ffffff' },
    objects: [
      {
        id: 'serif', type: 'textFrame', name: 'serif',
        transform: { x: 40, y: 40, width: 400, height: 120, rotation: 0, scaleX: 1, scaleY: 1 },
        visible: true, locked: false, opacity: 1, blendMode: 'normal',
        style: { fontFamily: 'Times New Roman, Times, serif', fontSize: 22, lineHeight: 1.4, letterSpacing: 0.01 },
        text: { blocks: [
          { kind: 'paragraph', runs: [
            { text: 'plain ' },
            { text: 'bold', format: { bold: true } },
            { text: ' and ' },
            { text: 'italic', format: { italic: true } },
            { text: ' one\\ntwo' },
          ] },
        ] },
      },
      {
        id: 'mono', type: 'textFrame', name: 'mono',
        transform: { x: 40, y: 200, width: 400, height: 120, rotation: 0, scaleX: 1, scaleY: 1 },
        visible: true, locked: false, opacity: 1, blendMode: 'normal',
        style: { fontFamily: 'Courier New, Courier, monospace', fontSize: 14, lineHeight: 1.2, color: '#333333' },
        text: { blocks: [
          { kind: 'paragraph', align: 'center', runs: [
            { text: 'under', format: { underline: true } },
            { text: 'struck', format: { strike: true } },
          ] },
        ] },
      },
    ],
  }],
})`;

/** The Arabic frame, kept separate because its content stream is asserted on its own. */
const ARABIC_FIXTURE = `() => ({
  formatVersion: 3, id: 'arabic', name: 'Arabic',
  pageSetup: { fixedSize: true, defaultSize: { width: 210, height: 297, unit: 'mm', orientation: 'portrait' }, resizeBehaviour: 'crop' },
  styles: [],
  assets: {},
  pages: [{
    id: 'p1', name: '1',
    size: { width: 210, height: 297, unit: 'mm', orientation: 'portrait' },
    background: { type: 'solid', color: '#ffffff' },
    objects: [{
      id: 'ar', type: 'textFrame', name: 'ar',
      transform: { x: 40, y: 40, width: 400, height: 120, rotation: 0, scaleX: 1, scaleY: 1 },
      visible: true, locked: false, opacity: 1, blendMode: 'normal',
      text: { blocks: [{ kind: 'paragraph', runs: [{ text: 'مرحبا بالعالم' }] }] },
    }],
  }],
})`;

/**
 * Generates a real PDF through the print engine.
 *
 * `preferCSSPageSize` matters: without it Chromium overrides the sheet with its own default paper,
 * and the resulting `/MediaBox` would describe a page the document never asked for.
 */
async function generatePdf(page: Page, source: string): Promise<string> {
  await mountFixture(page, source);
  await settle(page);
  await page.emulateMedia({ media: 'print' });
  const pdf = await page.pdf({ printBackground: true, preferCSSPageSize: true });
  // Latin-1 keeps single-byte PDF operators readable; the bytes we look for are ASCII.
  return pdf.toString('latin1');
}

/** The distinct font names the PDF embedded. */
function embeddedFonts(pdf: string): string[] {
  return [...pdf.matchAll(/\/BaseFont\s*\/([A-Za-z0-9+#-]+)/g)].map((match) => match[1] ?? '');
}

/** Each `/MediaBox` as `[width, height]` in points, the way `print-mixed-size` reads them. */
function mediaBoxes(pdf: string): Array<[number, number]> {
  return [...pdf.matchAll(/\/MediaBox\s*\[\s*([\d.\s-]+?)\]/g)].map((match) => {
    const numbers = (match[1] ?? '')
      .trim()
      .split(/\s+/)
      .map(Number);
    return [numbers[2] ?? 0, numbers[3] ?? 0];
  });
}

test.describe('typography reaches the exported PDF', () => {
  test('the authored font families are the ones embedded', async ({ page }) => {
    const pdf = await generatePdf(page, TYPOGRAPHY_FIXTURE);
    const fonts = embeddedFonts(pdf);

    expect(fonts.length, 'the PDF embedded no fonts at all').toBeGreaterThan(0);
    // PDF font names are subset-prefixed, so `ABCDEF+TimesNewRoman` is the normal form of the
    // family "Times New Roman". Matching on the unspaced, subset-stripped name is what survives.
    const joined = fonts.join(' ');
    expect(
      joined.replace(/\+/g, ''),
      `neither authored family is in the PDF's fonts: ${joined}`,
    ).toMatch(/TimesNewRoman/i);
    expect(joined.replace(/\+/g, '')).toMatch(/CourierNew|Courier/i);
  });

  test('a page of styled text is still one sheet, at the page size the document asked for', async ({ page }) => {
    // The claim that typography does not change pagination. Two frames, one page, and both with
    // non-default typography -- so if the sheet count moved, this would catch it.
    const pdf = await generatePdf(page, TYPOGRAPHY_FIXTURE);
    expect([...pdf.matchAll(/\/Type\s*\/Page[^s]/g)].length, 'typography changed the sheet count').toBe(1);

    // Compared numerically, not against a literal. A4 portrait is 595x842pt, but Chromium's
    // millimetre-to-point conversion rounds to 594.96x841.92, and a regex written for 595 would
    // fail on a correct export -- which is how a test ends up asserting the wrong number.
    const [box] = mediaBoxes(pdf);
    expect(box?.[0]).toBeCloseTo(595, 0);
    expect(box?.[1]).toBeCloseTo(842, 0);
  });

  test('Arabic characters survive export as text', async ({ page }) => {
    // Content stream, not screen. PDF text is stored as glyph indices, so this asserts the *font*
    // is embedded rather than the literal characters -- which is the honest claim at this level, and
    // the one that would fail if the export dropped the frame entirely.
    const pdf = await generatePdf(page, ARABIC_FIXTURE);
    expect(embeddedFonts(pdf).length, 'the Arabic frame embedded no font, so nothing was exported').toBeGreaterThan(0);
    // An Arabic page with no embedded font would still be one page, so the page count alone is not
    // evidence that anything was drawn.
    expect([...pdf.matchAll(/\/Type\s*\/Page[^s]/g)].length).toBe(1);
  });

  test('a frame with no font stack still prints, using a fallback', async ({ page }) => {
    // The contract `fontFamily` carries: absence means "CSS decides", never "renders nothing".
    const pdf = await generatePdf(page, ARABIC_FIXTURE);
    expect(embeddedFonts(pdf).length, 'a frame with no style produced no embedded font').toBeGreaterThan(0);
  });
});
